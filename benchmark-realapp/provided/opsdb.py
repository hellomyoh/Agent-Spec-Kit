"""OpsBoard — provided in-memory schema-declarative store (the "database engine").

This is INFRASTRUCTURE given to every group (like Postgres). Agents declare
schemas and run queries against it; they do NOT edit this file. The realistic
constraint it enforces: writing an undeclared column or the wrong type is an
error (a real migration/schema mismatch), so FE/BE/DB field drift surfaces here.

Deterministic: sequential ids, no clock, no randomness.
"""
from __future__ import annotations
import copy


class SchemaError(Exception):
    pass


# allowed column type tags
_PY = {"int": int, "str": str, "bool": bool, "float": (int, float)}


class Database:
    def __init__(self):
        self._schema: dict[str, dict] = {}   # table -> {col: typetag}
        self._required: dict[str, set] = {}  # table -> required cols
        self._rows: dict[str, dict] = {}     # table -> {id: row}
        self._seq: dict[str, int] = {}

    # ---- schema ----
    def define_table(self, table: str, columns: dict, required=None):
        """columns: {name: typetag}. typetag in int/str/bool/float, 'enum:a|b',
        or 'ref:other_table'. 'id' is implicit (auto int PK)."""
        for col, tag in columns.items():
            base = tag.split(":", 1)[0]
            if base not in ("int", "str", "bool", "float", "enum", "ref"):
                raise SchemaError(f"{table}.{col}: unknown type tag {tag!r}")
        self._schema[table] = dict(columns)
        self._required[table] = set(required or columns.keys())
        self._rows.setdefault(table, {})
        self._seq.setdefault(table, 0)

    def tables(self):
        return list(self._schema)

    # ---- validation ----
    def _check(self, table, row, *, partial: bool):
        if table not in self._schema:
            raise SchemaError(f"unknown table {table!r}")
        schema = self._schema[table]
        for col in row:
            if col == "id":
                continue
            if col not in schema:
                raise SchemaError(f"{table}: undeclared column {col!r}")
            self._check_type(table, col, schema[col], row[col])
        if not partial:
            missing = self._required[table] - set(row) - {"id"}
            if missing:
                raise SchemaError(f"{table}: missing required {sorted(missing)}")

    def _check_type(self, table, col, tag, val):
        if val is None:
            return
        base, _, arg = tag.partition(":")
        if base in _PY:
            if not isinstance(val, _PY[base]) or (base != "bool" and isinstance(val, bool)):
                raise SchemaError(f"{table}.{col}: expected {base}, got {val!r}")
        elif base == "enum":
            allowed = arg.split("|")
            if val not in allowed:
                raise SchemaError(f"{table}.{col}: {val!r} not in {allowed}")
        elif base == "ref":
            if not isinstance(val, int):
                raise SchemaError(f"{table}.{col}: ref must be int id, got {val!r}")

    # ---- CRUD ----
    def insert(self, table, row: dict) -> int:
        self._check(table, row, partial=False)
        self._seq[table] += 1
        rid = self._seq[table]
        stored = copy.deepcopy(row)
        stored["id"] = rid
        self._rows[table][rid] = stored
        return rid

    def get(self, table, rid):
        if table not in self._rows:
            raise SchemaError(f"unknown table {table!r}")
        r = self._rows[table].get(rid)
        return copy.deepcopy(r) if r else None

    def update(self, table, rid, changes: dict):
        self._check(table, changes, partial=True)
        if rid not in self._rows.get(table, {}):
            raise SchemaError(f"{table}: no row id={rid}")
        self._rows[table][rid].update(copy.deepcopy(changes))
        return copy.deepcopy(self._rows[table][rid])

    def query(self, table, **filters):
        if table not in self._rows:
            raise SchemaError(f"unknown table {table!r}")
        out = []
        for r in self._rows[table].values():
            if all(r.get(k) == v for k, v in filters.items()):
                out.append(copy.deepcopy(r))
        return sorted(out, key=lambda x: x["id"])

    def all(self, table):
        return self.query(table)
