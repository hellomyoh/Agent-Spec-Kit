"""OpsBoard — provided in-memory TTL cache (the "Redis").

INFRASTRUCTURE given to every group. Agents choose keys, TTLs and *when to
invalidate*; they do NOT edit this file. Because the store does not auto-expire
on writes elsewhere, forgetting to invalidate after a mutation yields a STALE
read — observable through the app's public surface (dashboard/list render).

Deterministic: time is an injected integer clock (tick), advanced explicitly by
the harness. No wall-clock, no randomness.
"""
from __future__ import annotations
import copy


class Clock:
    def __init__(self, t=0):
        self.t = t

    def tick(self, n=1):
        self.t += n
        return self.t

    def now(self):
        return self.t


class Cache:
    def __init__(self, clock: Clock | None = None):
        self.clock = clock or Clock()
        self._store: dict[str, tuple] = {}  # key -> (value, expire_at|None)
        self.stats = {"hits": 0, "misses": 0, "sets": 0, "invalidations": 0}
        self.log: list[tuple] = []          # (op, key) audit trail for checkers

    def set(self, key: str, value, ttl: int | None = None):
        exp = None if ttl is None else self.clock.now() + ttl
        self._store[key] = (copy.deepcopy(value), exp)
        self.stats["sets"] += 1
        self.log.append(("set", key))

    def get(self, key: str):
        item = self._store.get(key)
        if item is None:
            self.stats["misses"] += 1
            self.log.append(("miss", key))
            return None
        value, exp = item
        if exp is not None and self.clock.now() >= exp:
            del self._store[key]
            self.stats["misses"] += 1
            self.log.append(("expire", key))
            return None
        self.stats["hits"] += 1
        self.log.append(("hit", key))
        return copy.deepcopy(value)

    def invalidate(self, key: str):
        if key in self._store:
            del self._store[key]
        self.stats["invalidations"] += 1
        self.log.append(("invalidate", key))

    def invalidate_prefix(self, prefix: str):
        for k in [k for k in self._store if k.startswith(prefix)]:
            del self._store[k]
        self.stats["invalidations"] += 1
        self.log.append(("invalidate_prefix", prefix))

    def keys(self):
        return sorted(self._store)
